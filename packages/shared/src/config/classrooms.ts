export const ClassroomList: [string, number][] = Object.entries(Classrooms);

export const ClassroomNameById: Record<number, string> = Object.fromEntries(
	ClassroomList.map(([name, id]) => [id, name]),
);

/** Поиск кабинетов по части названия (регистр не важен). */
export function searchClassrooms(query: string, limit = 20): [string, number][] {
	const needle = query.trim().toLowerCase();
	if (!needle) return [];
	return ClassroomList.filter(([name]) => name.toLowerCase().includes(needle)).slice(0, limit);
}
